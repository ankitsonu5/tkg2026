// Creates frontend/.env and backend/.env on the server when they do not exist yet, from the
// old single-app .env that the Payload deployment used (repo root `.env`, else `.env.production`).
// Existing files are never overwritten; a missing INTERNAL_API_KEY is generated and written to
// both. Run by deploy/deploy.sh — safe to run on every deploy.
const crypto = require('crypto')
const fs = require('fs')
const net = require('net')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const FRONTEND_ENV = path.join(ROOT, 'frontend', '.env')
const BACKEND_ENV = path.join(ROOT, 'backend', '.env')
const STAGING_URL = 'https://new.telkganesan.com'

function parse(file) {
  if (!fs.existsSync(file)) return null
  const out = {}
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*?)\s*$/)
    if (m) out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2')
  }
  return out
}

function write(file, lines) {
  fs.writeFileSync(file, lines.join('\n') + '\n', { mode: 0o600 })
  console.log(`created ${path.relative(ROOT, file)}`)
}

/** Writes or replaces one KEY=value line in an existing .env file. */
function setKey(file, key, value) {
  const text = fs.readFileSync(file, 'utf8')
  const re = new RegExp(`^\\s*(?:export\\s+)?${key}\\s*=.*$`, 'm')
  fs.writeFileSync(file, re.test(text) ? text.replace(re, `${key}=${value}`) : `${text.replace(/\n?$/, '\n')}${key}=${value}\n`)
}

function portFree(port) {
  return new Promise((resolve) => {
    const server = net.createServer()
    server.once('error', () => resolve(false))
    server.once('listening', () => server.close(() => resolve(true)))
    server.listen(port, '127.0.0.1')
  })
}

async function freePort(start) {
  for (let port = start; port < start + 100; port++) if (await portFree(port)) return port
  throw new Error(`no free port between ${start} and ${start + 99}`)
}

async function main() {
  const fe = parse(FRONTEND_ENV)
  const be = parse(BACKEND_ENV)
  const key = be?.INTERNAL_API_KEY || fe?.INTERNAL_API_KEY || crypto.randomBytes(32).toString('hex')

  if (!fe || !be) {
    const old = parse(path.join(ROOT, '.env')) || parse(path.join(ROOT, '.env.production'))
    if (!old) {
      console.error('ERROR: frontend/.env or backend/.env is missing and there is no old root .env to build them from.')
      console.error('       Copy frontend/.env.example and backend/.env.example, fill them in, and run again.')
      process.exit(1)
    }
    if (!old.DATABASE_URI) {
      console.error('ERROR: the old root .env has no DATABASE_URI.')
      process.exit(1)
    }
    const siteUrl = /^https:\/\//.test(old.NEXT_PUBLIC_SERVER_URL || '') ? old.NEXT_PUBLIC_SERVER_URL : STAGING_URL

    let apiPort = be?.API_PORT
    if (!be) {
      // 4000 is often taken on a shared server, so start the search higher.
      apiPort = String(await freePort(4100))
      write(BACKEND_ENV, [
        '# Generated by deploy/setup-env.cjs from the old root .env. Never commit this file.',
        `API_PORT=${apiPort}`,
        'API_HOST=127.0.0.1',
        `DATABASE_URI=${old.DATABASE_URI}`,
        `INTERNAL_API_KEY=${key}`,
        `APP_SECRET=${old.APP_SECRET || old.PAYLOAD_SECRET || crypto.randomBytes(32).toString('hex')}`,
        `PUBLIC_SITE_URL=${siteUrl}`,
        `SMTP_HOST=${old.SMTP_HOST || ''}`,
        `SMTP_PORT=${old.SMTP_PORT || ''}`,
        `SMTP_USER=${old.SMTP_USER || ''}`,
        `SMTP_PASSWORD=${old.SMTP_PASSWORD || ''}`,
        `MAIL_FROM_ADDRESS=${old.MAIL_FROM_ADDRESS || ''}`,
        `MAIL_FROM_NAME=${old.MAIL_FROM_NAME || ''}`,
        `CRON_SECRET=${old.CRON_SECRET || ''}`,
        'MEDIA_DIR=media',
        `BLOB_READ_WRITE_TOKEN=${old.BLOB_READ_WRITE_TOKEN || ''}`,
        'NODE_ENV=production',
      ])
    }
    if (!fe) {
      write(FRONTEND_ENV, [
        '# Generated by deploy/setup-env.cjs from the old root .env. Never commit this file.',
        `APP_PORT=${old.APP_PORT || '3015'}`,
        `BACKEND_URL=http://127.0.0.1:${apiPort || '4000'}`,
        `INTERNAL_API_KEY=${key}`,
        `NEXT_PUBLIC_SERVER_URL=${siteUrl}`,
        `NEXT_PUBLIC_GA4_MEASUREMENT_ID=${old.NEXT_PUBLIC_GA4_MEASUREMENT_ID || ''}`,
        `PRODUCTION_ORIGIN=${old.PRODUCTION_ORIGIN || ''}`,
        `ALLOW_INDEXING=${old.ALLOW_INDEXING || ''}`,
      ])
    }
  }

  // Both files exist now; make sure they share the same internal key.
  for (const file of [BACKEND_ENV, FRONTEND_ENV]) {
    if (parse(file).INTERNAL_API_KEY !== key) {
      setKey(file, 'INTERNAL_API_KEY', key)
      console.log(`set INTERNAL_API_KEY in ${path.relative(ROOT, file)}`)
    }
  }
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
